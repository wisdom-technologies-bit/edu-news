/** Sources that are actually collected. */
export const ACTIVE_SOURCES: SourceDef[] = SOURCES.filter((s) => !s.disabled);

export function getSource(id: string): SourceDef | undefined {
  return SOURCES.find((s) => s.id === id);
}

export function sourceIndex(): Map<string, SourceDef> {
  return new Map(SOURCES.map((s) => [s.id, s]));
}

/** Domains owned by registry publishers — used to attribute discovery hits. */
export const PUBLISHER_HOSTS: Map<string, SourceDef> = new Map(
  SOURCES.flatMap((s) => {
    const hosts: [string, SourceDef][] = [];
    try {
      hosts.push([new URL(s.homepage).hostname.replace(/^www\./, ''), s]);
    } catch {
      /* ignore malformed homepage */
    }
    return hosts;
  }),
);
